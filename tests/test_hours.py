"""이용시간 문장 파서(tools/hours.py)와 그 시각에 여는지 판정을 가짜 문장으로 확인한다 (코스 품질 T4). 네트워크 · 모델을 쓰지 않는다."""
import pytest

from tools.hours import describe, open_at, parse_hours

H = lambda h, m=0: h * 60 + m


def ok(text, ranges, breaks=()):
    got = parse_hours(text)
    assert got == {"status": "open_close", "ranges": ranges, "breaks": list(breaks)}, got


# --- 읽는 모양 ---
def test_하나의_시간대():
    ok("09:00~17:30", [(H(9), H(17, 30))])
    ok("- 10:00~19:00", [(H(10), H(19))])
    ok("09:00-19:00", [(H(9), H(19))])
    ok("9:30 ~ 18:00", [(H(9, 30), H(18))])


def test_매일_같은_말이_붙어도_읽는다():
    ok("매일 10:00 - 22:00", [(H(10), H(22))])
    ok("영업시간 10:00~22:00", [(H(10), H(22))])


def test_마지막_주문_입장_마감은_읽지_않고_닫는_시각만_쓴다():
    ok("10:00~19:00 (입장 마감 18:00)", [(H(10), H(19))])
    ok("10:00~19:00 (마지막 주문 18:30)", [(H(10), H(19))])
    ok("11:30~21:30 (마지막 주문 14:30 , 20:30)", [(H(11, 30), H(21, 30))])
    ok("10:00~18:00 (17:30 입장마감)", [(H(10), H(18))])
    ok("10:00~18:00 (주문 마감시간 17:00)", [(H(10), H(18))])
    ok("10:00~18:00 (전화문의)", [(H(10), H(18))])
    ok("09:00~18:00※ 자세한 사항은 전화문의 요망", [(H(9), H(18))])


def test_브레이크타임을_읽는다():
    ok("11:30~21:30 (준비시간 15:00~17:00) (마지막 주문 14:30 , 20:30)", [(H(11, 30), H(21, 30))], [(H(15), H(17))])
    ok("- 11:00~21:00- 준비시간 15:00~17:00- 마지막 주문 20:30", [(H(11), H(21))], [(H(15), H(17))])
    ok("09:00~18:00 (휴게시간: 12:00~13:00)※ 강좌에 따라 변동 가능", [(H(9), H(18))], [(H(12), H(13))])
    ok("11:30 ~ 21:00 (15:00~17:00 브레이크 타임)", [(H(11, 30), H(21))], [(H(15), H(17))])
    ok("11:00 - 21:00 (15:00 - 17:00 브레이크타임)", [(H(11), H(21))], [(H(15), H(17))])


def test_24시간_상시_개방은_하루_종일():
    for t in ("상시 개방", "24시간 영업", "24시간", "00:00~24:00", "상시 개방※ 자세한 크루즈선 정보는 홈페이지 참조"):
        assert parse_hours(t)["status"] == "all_day", t


def test_자정을_넘기는_영업():
    ok("18:00~02:00", [(H(18), H(26))])
    got = parse_hours("18:00~02:00")
    assert open_at(got, H(23)) == "open" and open_at(got, H(1)) == "open" and open_at(got, H(2)) == "closed" and open_at(got, H(10)) == "closed"
    ok("12:00~01:00", [(H(12), H(25))])
    ok("11:00~24:00", [(H(11), H(24))])


def test_이어지지_않는_여러_시간대():
    ok("11:30~15:00 / 17:00~22:00", [(H(11, 30), H(15)), (H(17), H(22))])


# --- 읽지 않는 모양(unknown) ---
@pytest.mark.parametrize("text", [
    "- 평일 09:00~18:00- 주말 10:00~17:00",      # 요일 조건
    "월요일~토요일 10:00~18:00", "화~일 10:00 - 21:00", "월~금 10:00-18:00 토,일 10:00-20:00",
    "[하절기] 09:00~18:00[동절기] 09:00~17:00",   # 계절
    "- 하절기(3월~10월) 10:30~18:00- 동절기(11월~2월) 10:30~17:00",
    "- 11:00~21:00- 준비시간 15:00~17:00※ 주말에는 준비시간 없이 영업",   # 안내문의 요일 조건
    "[1층]- 11:30~22:30 [2층]- 11:30~21:30",      # 구역별
    "[문헌정보실] 09:00~20:00 [열람실] 07:00~22:00",
    "10:00~18:00 / 10:00~20:00",                  # 겹치는 구간(갈래일 수 있다)
    "10:00~18:00 (단체만 가능)",                   # 괄호 속 조건
    "상시 개방 (카페 우유부단 10:00~18:00)",
    "상시 개방- 해수욕장 개장 09:00~18:00",
    "09:00~일몰", "공연 별로 상이함", "※ 자세한 사항은 전화문의 요망", "홈페이지 참조",
    "10:00~21::30", "25:00~26:00", "10:00~10:00", "24시간 (준비시간 04:00~05:00)",
    "", "   ", None, 123, [],
])
def test_읽을_수_없으면_unknown(text):
    assert parse_hours(text) == {"status": "unknown", "ranges": [], "breaks": []}


# --- 그 시각에 여는가 ---
def test_개장_폐장_경계는_시작은_포함_끝은_제외():
    t = "10:00~18:00"
    assert [open_at(t, m) for m in (H(9, 59), H(10), H(17, 59), H(18))] == ["closed", "open", "open", "closed"]


def test_쉬는_시간에는_닫은_것으로_본다():
    t = "11:30~21:30 (준비시간 15:00~17:00)"
    assert [open_at(t, m) for m in (H(12), H(15), H(16, 30), H(17), H(18, 30))] == ["open", "closed", "closed", "open", "open"]


def test_하루_종일과_읽지_못한_문장():
    assert open_at("상시 개방", H(3)) == "open"
    assert open_at("평일 10:00~18:00 주말 10:00~20:00", H(3)) == "check" and open_at("", H(12)) == "check" and open_at(None, H(12)) == "check"


def test_describe는_읽은_값만_옮긴다():
    assert describe(parse_hours("11:30~21:30 (준비시간 15:00~17:00)")) == "11:30~21:30, 쉬는 시간 15:00~17:00"
    assert describe(parse_hours("18:00~02:00")) == "18:00~02:00" and describe(parse_hours("상시 개방")) == "24시간"
